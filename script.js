// ============================================================
// PAGE CONTROL
// ============================================================

function showPage(page) {
  homePage.classList.remove("active");
  quizPage.classList.remove("active");
  resultPage.classList.remove("active");

  page.classList.add("active");

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });
}


// ============================================================
// SHUFFLE
// ============================================================

function shuffle(array) {
  const copy = [...array];

  for (let i = copy.length - 1; i > 0; i--) {
    const random = Math.floor(Math.random() * (i + 1));

    [copy[i], copy[random]] = [copy[random], copy[i]];
  }

  return copy;
}


// ============================================================
// START QUIZ
// ============================================================

function startQuiz(category = selectedCategory) {

  selectedCategory = category;

  let pool;

  if (category === "All") {
    pool = questions;
  } else {
    pool = questions.filter(q => q.category === category);
  }

  // Randomize questions
  quizQuestions = shuffle(pool).slice(0, 20);

  currentQuestion = 0;
  score = 0;

  showPage(quizPage);

  loadQuestion();
}


// ============================================================
// LOAD QUESTION
// ============================================================

function loadQuestion() {

  clearInterval(timerInterval);

  answered = false;
  nextBtn.disabled = true;

  const question = quizQuestions[currentQuestion];

  if (!question) {
    finishQuiz();
    return;
  }

  questionText.textContent = question.question;

  quizCategory.textContent = question.category;

  questionNumber.textContent =
    `Question ${currentQuestion + 1} of ${quizQuestions.length}`;

  questionBadge.textContent =
    `QUESTION ${String(currentQuestion + 1).padStart(2, "0")}`;

  scoreText.textContent = `Score: ${score}`;

  const progress =
    ((currentQuestion) / quizQuestions.length) * 100;

  progressBar.style.width = `${progress}%`;

  optionsContainer.innerHTML = "";

  const shuffledOptions = question.options.map((text, index) => ({
    text,
    originalIndex: index
  }));

  const randomOptions = shuffle(shuffledOptions);

  randomOptions.forEach((option, index) => {

    const button = document.createElement("button");

    button.className = "option";

    button.innerHTML = `
      <span class="option-letter">
        ${String.fromCharCode(65 + index)}
      </span>

      <span>${option.text}</span>
    `;

    button.addEventListener("click", () => {
      selectAnswer(button, option.originalIndex);
    });

    optionsContainer.appendChild(button);
  });

  startTimer();
}


// ============================================================
// TIMER
// ============================================================

function startTimer() {

  timeLeft = 20;

  timerElement.textContent = timeLeft;
  timerElement.parentElement.classList.remove("warning");

  timerInterval = setInterval(() => {

    timeLeft--;

    timerElement.textContent = timeLeft;

    if (timeLeft <= 5) {
      timerElement.parentElement.classList.add("warning");
    }

    if (timeLeft <= 0) {
      clearInterval(timerInterval);

      revealAnswer(null);

      setTimeout(() => {
        nextQuestion();
      }, 900);
    }

  }, 1000);
}


// ============================================================
// SELECT ANSWER
// ============================================================

function selectAnswer(button, selectedIndex) {

  if (answered) return;

  answered = true;

  clearInterval(timerInterval);

  revealAnswer(selectedIndex);
}


// ============================================================
// REVEAL ANSWER
// ============================================================

function revealAnswer(selectedIndex) {

  const question = quizQuestions[currentQuestion];

  const optionButtons =
    document.querySelectorAll(".option");

  optionButtons.forEach(button => {
    button.classList.add("disabled");
  });

  if (selectedIndex === question.answer) {

    score++;

    optionButtons.forEach(button => {

      const text = button.querySelector("span:last-child").textContent;

      if (text === question.options[question.answer]) {
        button.classList.add("correct");
      }

    });

  } else {

    optionButtons.forEach(button => {

      const text = button.querySelector("span:last-child").textContent;

      if (text === question.options[question.answer]) {
        button.classList.add("correct");
      }
    });

    if (selectedIndex !== null) {

      optionButtons.forEach(button => {

        const text =
          button.querySelector("span:last-child").textContent;

        if (text === question.options[selectedIndex]) {
          button.classList.add("wrong");
        }
      });
    }
  }

  scoreText.textContent = `Score: ${score}`;

  nextBtn.disabled = false;
}


// ============================================================
// NEXT QUESTION
// ============================================================

function nextQuestion() {

  if (!answered) return;

  currentQuestion++;

  if (currentQuestion >= quizQuestions.length) {
    finishQuiz();
  } else {
    loadQuestion();
  }
}


// ============================================================
// FINISH QUIZ
// ============================================================

function finishQuiz() {

  clearInterval(timerInterval);

  progressBar.style.width = "100%";

  showPage(resultPage);

  const total = quizQuestions.length;

  const wrong = total - score;

  const accuracy = Math.round((score / total) * 100);

  document.getElementById("finalScore").textContent = score;

  document.getElementById("correctAnswers").textContent = score;

  document.getElementById("wrongAnswers").textContent = wrong;

  document.getElementById("accuracy").textContent =
    `${accuracy}%`;

  const message = document.getElementById("resultMessage");

  const description =
    document.getElementById("resultDescription");

  if (accuracy >= 90) {

    message.textContent = "Outstanding! 🔥";

    description.textContent =
      "Your knowledge is seriously impressive.";

  } else if (accuracy >= 75) {

    message.textContent = "Excellent Work! 🚀";

    description.textContent =
      "You have a very strong knowledge base.";

  } else if (accuracy >= 50) {

    message.textContent = "Good Job! 💪";

    description.textContent =
      "Keep practicing and you will improve even more.";

  } else {

    message.textContent = "Keep Learning! 🧠";

    description.textContent =
      "Every question is a chance to learn something new.";
  }
}


