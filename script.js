// ============================================================
// KEYBOARD SUPPORT
// ============================================================

document.addEventListener("keydown", event => {

  if (!quizPage.classList.contains("active")) {
    return;
  }

  if (event.key >= "1" && event.key <= "4") {

    const index =
      Number(event.key) - 1;

    const buttons =
      document.querySelectorAll(".option");

    if (buttons[index] && !answered) {
      buttons[index].click();
    }
  }

  if (event.key === "Enter" && answered) {
    nextQuestion();
  }

});